#!/usr/bin/env node
// dsh-oneclick · MCP block generator
// Probes this machine for the MCP servers that were present on the source box
// and rewrites the marked region of cordis.patch.yml. Missing servers are
// silently skipped, so a fresh machine never boots with dangling paths.
//
// usage: node gen-mcp.mjs <path/to/cordis.patch.yml> [--dry-run]

import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import net from 'node:net'

const isWin = process.platform === 'win32'
const HOME = os.homedir()
const LOCAL_PROGRAMS = isWin
  ? path.join(process.env.LOCALAPPDATA || path.join(HOME, 'AppData', 'Local'), 'Programs')
  : '/Applications'
const MAGPIE_NPM = path.join(HOME, '.config', 'magpie', 'mcp-npm')

const exists = (p) => { try { return fs.existsSync(p) } catch { return false } }

function which(bin) {
  const exts = isWin ? ['.exe', '.cmd', '.bat', ''] : ['']
  const dirs = (process.env.PATH || '').split(path.delimiter).filter(Boolean)
  for (const d of dirs) {
    for (const e of exts) {
      const p = path.join(d, bin + e)
      if (exists(p)) return p
    }
  }
  return null
}

function findMagpieModule(suffix) {
  if (!exists(MAGPIE_NPM)) return null
  for (const hash of fs.readdirSync(MAGPIE_NPM)) {
    const p = path.join(MAGPIE_NPM, hash, 'node_modules', suffix)
    if (exists(p)) return p
  }
  return null
}

function tcpProbe(port, timeoutMs = 400) {
  return new Promise((resolve) => {
    const sock = net.connect({ host: '127.0.0.1', port })
    const done = (ok) => { try { sock.destroy() } catch {} ; resolve(ok) }
    sock.setTimeout(timeoutMs)
    sock.once('connect', () => done(true))
    sock.once('timeout', () => done(false))
    sock.once('error', () => done(false))
  })
}

async function buildCandidates() {
  const list = []

  // 1) crm-lan-ci (python MCP)
  const crmPython = path.join(LOCAL_PROGRAMS, 'CRM-LAN-CI-MCP', '.venv', isWin ? 'Scripts' : 'bin', isWin ? 'python.exe' : 'python')
  const crmServer = path.join(LOCAL_PROGRAMS, 'CRM-LAN-CI-MCP', 'server.py')
  if (exists(crmPython) && exists(crmServer)) {
    list.push({
      id: 'magpie-mcp-crm-lan-ci', serverName: 'crm-lan-ci', transport: 'stdio',
      command: crmPython, args: ['-I', crmServer]
    })
  }

  // 2) github-review (go binary)
  const ghCandidates = [
    path.join(LOCAL_PROGRAMS, 'GitHub-MCP', '2.2.0', isWin ? 'github-mcp-server.exe' : 'github-mcp-server'),
    which('github-mcp-server')
  ].filter(Boolean)
  const ghBin = ghCandidates.find(exists)
  if (ghBin) {
    list.push({
      id: 'magpie-mcp-github-review', serverName: 'github-review', transport: 'stdio',
      command: ghBin, args: ['stdio', '--read-only', '--toolsets', 'repos,pull_requests,actions', '--oauth-scopes', 'repo']
    })
  }

  // 3) magpie hub (streamable http)
  if (await tcpProbe(3425)) {
    list.push({
      id: 'magpie-mcp-magpie', serverName: 'magpie', transport: 'streamable-http',
      url: 'http://127.0.0.1:3425/mcp/magpie/hub/dsh'
    })
  }

  // 4) aoci-code
  const aoci = which('aoci')
  if (aoci) {
    list.push({ id: 'magpie-mcp-aoci-code', serverName: 'aoci-code', transport: 'stdio', command: aoci, args: ['mcp'] })
  }

  // 5) chrome-devtools (via magpie npm cache)
  const cdt = findMagpieModule(path.join('chrome-devtools-mcp', 'out', 'Default', 'gen', 'src', 'bin', 'chrome-devtools-mcp.js'))
  if (cdt) {
    const node = process.execPath
    list.push({
      id: 'magpie-mcp-chrome-devtools', serverName: 'chrome-devtools', transport: 'stdio',
      command: node,
      args: [cdt, '--headless', '--isolated', '--no-usage-statistics', '--no-performance-crux']
    })
  }

  // 6) ida-pro-mcp
  const idalib = which('idalib-mcp')
  if (idalib) {
    const idaDirs = [
      'C:/Program Files/IDA Professional 9.3',
      'C:/Program Files/IDA Professional 9.2',
      'C:/Program Files/IDA Pro 9.3',
      '/Applications/IDA Professional 9.3.app/Contents/MacOS'
    ]
    const idaDir = idaDirs.find(exists)
    const entry = { id: 'magpie-mcp-ida-pro-mcp', serverName: 'ida-pro-mcp', transport: 'stdio', command: idalib, args: ['--stdio'] }
    if (idaDir) entry.env = { IDADIR: idaDir }
    list.push(entry)
  }

  // 7) shadcn (via magpie npm cache)
  const shadcn = findMagpieModule(path.join('shadcn', 'dist', 'index.js'))
  if (shadcn) {
    list.push({
      id: 'magpie-mcp-shadcn', serverName: 'shadcn', transport: 'stdio',
      command: process.execPath, args: [shadcn, 'mcp']
    })
  }

  return list
}

const q = (s) => JSON.stringify(String(s))

function renderBlock(candidates) {
  const lines = []
  lines.push('# >>> MCP_AUTO_BEGIN')
  lines.push('# generated by tools/gen-mcp.mjs — only servers detected on THIS machine')
  if (candidates.length === 0) {
    lines.push('# (no optional MCP server detected; edit below to add your own)')
  }
  for (const c of candidates) {
    lines.push('- insert:')
    lines.push(`    # auto-detected: ${c.serverName}`)
    lines.push(`    - id: ${c.id}`)
    lines.push('      name: "@deepseek-ai/dsh-mcp-client"')
    lines.push('      config:')
    lines.push(`        serverName: ${q(c.serverName)}`)
    lines.push(`        transport: ${q(c.transport)}`)
    if (c.url) {
      lines.push(`        url: ${q(c.url)}`)
    } else {
      lines.push(`        command: ${q(c.command)}`)
      if (c.args && c.args.length) {
        lines.push('        args:')
        for (const a of c.args) lines.push(`          - ${q(a)}`)
      }
      if (c.env) {
        lines.push('        env:')
        for (const [k, v] of Object.entries(c.env)) lines.push(`          ${k}: ${q(v)}`)
      }
    }
  }
  lines.push('# <<< MCP_AUTO_END')
  return lines.join('\n')
}

async function main() {
  const args = process.argv.slice(2)
  const dryRun = args.includes('--dry-run')
  const target = args.find((a) => !a.startsWith('--'))
  if (!target) {
    console.error('usage: node gen-mcp.mjs <cordis.patch.yml> [--dry-run]')
    process.exit(2)
  }
  if (!exists(target)) {
    console.error(`patch file not found: ${target}`)
    process.exit(2)
  }
  const candidates = await buildCandidates()
  const block = renderBlock(candidates)

  const src = fs.readFileSync(target, 'utf8')
  const begin = src.indexOf('# >>> MCP_AUTO_BEGIN')
  const end = src.indexOf('# <<< MCP_AUTO_END')
  let out
  if (begin !== -1 && end !== -1 && end > begin) {
    const tail = src.indexOf('\n', end)
    out = src.slice(0, begin) + block + (tail === -1 ? '\n' : src.slice(tail))
  } else if (begin === -1) {
    out = src.replace(/\s*$/, '\n\n') + block + '\n'
  } else {
    console.error('malformed MCP markers in patch file')
    process.exit(2)
  }

  console.log(`detected ${candidates.length} MCP server(s): ${candidates.map((c) => c.serverName).join(', ') || '(none)'}`)
  if (dryRun) {
    console.log(block)
    return
  }
  fs.writeFileSync(target, out)
  console.log(`patched ${target}`)
}

main().catch((e) => { console.error(e); process.exit(1) })
